# Regenerates src/openrgb_ids.rs from OpenRGB's udev rules (60-openrgb.rules, from an OpenRGB
# .deb or build). Only the device IDs and the controller names are taken: facts, not code.
#   python tools/gen_openrgb_ids.py path/to/60-openrgb.rules "1.1.50 git fc3aa07"
import re, sys

rules, version = sys.argv[1], sys.argv[2]
line_re = re.compile(r'idVendor}=="([0-9a-fA-F]{4})".*idProduct}=="([0-9a-fA-F]{4})".*TAG\+="([^"]+)"\s*$')
ids = {}
for line in open(rules, encoding="utf-8"):
    m = line_re.search(line.strip())
    if not m:
        continue
    vid, pid, tag = int(m[1], 16), int(m[2], 16), m[3].replace("_", " ")
    names = ids.setdefault(vid << 16 | pid, [])
    if tag not in names:
        names.append(tag)

joined = {k: " / ".join(v) for k, v in ids.items()}
names = sorted(set(joined.values()))
index = {n: i for i, n in enumerate(names)}
keys = sorted(joined)

out = []
out.append("// SPDX-License-Identifier: GPL-2.0-or-later")
out.append("// Credit: the OpenRGB project, https://gitlab.com/CalcProgrammer1/OpenRGB (GPL-2.0-or-later).")
out.append("// USB devices OpenRGB can control, as vendor<<16|product, sorted, each with the name of the")
out.append("// OpenRGB controller (= lighting protocol) that drives it.")
out.append(f"// Generated by tools/gen_openrgb_ids.py from OpenRGB's 60-openrgb.rules ({version}).")
out.append("// Used only to tell the user what a detected RGB device is; nothing here talks to hardware.")
out.append("")
out.append("/// The OpenRGB controller name for a USB device, if OpenRGB knows it.")
out.append("pub fn protocol(vid: u16, pid: u16) -> Option<&'static str> {")
out.append("    let key = ((vid as u32) << 16) | pid as u32;")
out.append("    OPENRGB_USB.binary_search_by_key(&key, |e| e.0).ok().map(|i| NAMES[OPENRGB_USB[i].1 as usize])")
out.append("}")
out.append("")
out.append("#[rustfmt::skip]")
out.append(f"const NAMES: [&str; {len(names)}] = [")
for n in names:
    out.append(f'    "{n}",')
out.append("];")
out.append("")
out.append("#[rustfmt::skip]")
out.append(f"const OPENRGB_USB: [(u32, u16); {len(keys)}] = [")
row = []
for k in keys:
    row.append(f"(0x{k:08X}, {index[joined[k]]})")
    if len(row) == 6:
        out.append("    " + ", ".join(row) + ",")
        row = []
if row:
    out.append("    " + ", ".join(row) + ",")
out.append("];")
open("src/openrgb_ids.rs", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(keys), "devices,", len(names), "controllers")
